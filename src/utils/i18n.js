export function useTranslation() {
  const { language } = useApp();

  const t = (key) => {
    const keys = key.split('.');
    let value = translations[language];
    for (const k of keys) {
      if (value == null) return key;
      value = value[k];
    }
    return value !== undefined && value !== null ? String(value) : key;
  };

  return { t, language };
}
